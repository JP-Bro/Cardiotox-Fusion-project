"""
audit_matches.py -- Data-driven audit of cohort compounds matched to LINCS by NAME (not InChIKey), plus
related drug forms that carry different labels. Writes results/name_match_audit.md.

For every name-matched compound it recomputes, from raw files:
  * Tanimoto (Morgan r=2, 2048) between the DICTrank structure and LINCS's canonical_smiles for the pert_id
  * heavy-atom difference, split membership, and whether the pert_id is used by any other cohort compound
and assigns a verdict by rule (not by hand):
  SAME      identical molecular formula after neutralisation + largest-fragment (tautomer / stereo /
            salt-stripping representation difference -- Morgan Tanimoto is unreliable for tautomers, so it is
            reported for information only)
  REVIEW    different formula (ester/phosphate prodrug, mixture component, different molecule) -- the LINCS
            expression then describes a related compound, not the exact structure used for the GNN
"""
import os, sys, gzip
import pandas as pd
from rdkit import Chem, DataStructs, RDLogger
from rdkit.Chem import AllChem, MolStandardize, rdMolDescriptors
RDLogger.DisableLog('rdApp.*')
sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from config import CFG

UNCH = MolStandardize.rdMolStandardize.Uncharger()
formula = lambda m: rdMolDescriptors.CalcMolFormula(UNCH.uncharge(m))
fp = lambda m: AllChem.GetMorganFingerprintAsBitVect(m, 2, 2048)

matched = pd.read_csv(CFG.LINCS_MATCHED_CSV)
scaf = pd.read_csv(os.path.join(CFG.DATA_DIR, 'splits', 'scaffold_split.csv')).set_index('parent_smiles')
pi = pd.read_csv(CFG.LINCS_PERT_INFO, sep='\t', dtype=str).set_index('pert_id')

rows = []
nm = matched[matched.match_method != 'inchikey']
for _, r in nm.iterrows():
    dm = Chem.MolFromSmiles(r.parent_smiles)
    lsmi = pi.loc[r.pert_id, 'canonical_smiles'] if r.pert_id in pi.index else None
    lm = Chem.MolFromSmiles(lsmi) if isinstance(lsmi, str) else None
    if lm is not None:
        frags = Chem.GetMolFrags(lm, asMols=True)
        lm = max(frags, key=lambda m: m.GetNumHeavyAtoms())
        sim = DataStructs.TanimotoSimilarity(fp(dm), fp(lm))
        dh = abs(dm.GetNumHeavyAtoms() - lm.GetNumHeavyAtoms())
        f_d, f_l = formula(dm), formula(lm)
    else:
        sim, dh, f_d, f_l = float('nan'), -1, '?', '?'
    verdict = 'SAME' if f_d == f_l else 'REVIEW'
    rows.append(dict(name=r.query_name, label=int(r.cardiotox_label), lincs=pi.loc[r.pert_id, 'pert_iname'],
                     pert_id=r.pert_id, tanimoto=round(sim, 2), d_heavy=dh, f_d=f_d, f_l=f_l,
                     split=scaf.loc[r.parent_smiles, 'split'],
                     shared=int((matched.pert_id == r.pert_id).sum() > 1), verdict=verdict))
df = pd.DataFrame(rows).sort_values(['verdict', 'tanimoto'])

# related forms with different labels (same name stem, different label), restricted to what reaches the cohort
lab = pd.read_csv(CFG.LABELS_CSV)
def stem(n):
    n = str(n).lower().strip()
    for s in CFG.SALT_SUFFIXES:
        if n.endswith(' ' + s):
            n = n[:-(len(s) + 1)].strip()
    return n
lab['stem'] = lab.resolved_name.map(stem)
cohort_stems = set(matched.query_name.map(stem))
g = lab.groupby('stem').agg(labels=('cardiotox_label', lambda x: sorted(set(x))), forms=('resolved_name', list))
conf = g[(g.labels.map(len) > 1) & g.index.isin(cohort_stems)]

out = os.path.join(CFG.RESULTS_DIR, 'name_match_audit.md')
with open(out, 'w', encoding='utf-8') as f:
    f.write("# Name-Matched Compound Audit (auto-generated by scripts/audit_matches.py)\n\n")
    f.write(f"{len(nm)} of {len(matched)} cohort compounds were matched to LINCS by stripped drug NAME because the InChIKey "
            "connectivity block did not match. Each is compared structurally against LINCS's own structure for the pert_id.\n\n")
    f.write("| DICTrank name | Label | LINCS pert_iname | Formula (DICTrank) | Formula (LINCS) | Tanimoto | Split | pert_id shared? | Verdict |\n|---|:-:|---|---|---|:-:|:-:|:-:|:-:|\n")
    for _, r in df.iterrows():
        f.write(f"| {r['name']} | {r.label} | {r.lincs} | {r.f_d} | {r.f_l} | {r.tanimoto} | {r.split} | {'YES' if r.shared else 'no'} | {r.verdict} |\n")
    nrev = int((df.verdict == 'REVIEW').sum())
    f.write(f"\n**{len(df) - nrev} SAME, {nrev} REVIEW.** REVIEW rows have a different molecular formula (prodrug, ester, mixture component): the LINCS "
            "expression belongs to a related compound, not the exact structure given to the GNN. Keep them only with that substitution declared in the methods, or drop them.\n\n")
    f.write("## Related forms carrying different labels (cohort compounds only)\n\n")
    if len(conf):
        f.write("Same drug stem, different DICTrank labels. The 'any toxic form -> 1' rule only merges forms with the "
                "SAME InChIKey block; forms with different blocks (e.g. a prodrug) are separate rows, so the cohort label for the "
                "kept form may disagree with its sibling.\n\n| Stem | Forms in DICTrank | Labels |\n|---|---|---|\n")
        for stem_, r in conf.iterrows():
            f.write(f"| {stem_} | {'; '.join(r.forms)} | {r.labels} |\n")
    else:
        f.write("None.\n")
print(open(out, encoding='utf-8').read())
